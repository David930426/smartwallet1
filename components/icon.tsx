export function Icon(name: string) {
  switch (name) {
    case "money_icon":
      return "💵"
    case "star_icon":
      return "⭐"
    case "food_icon":
      return "🍔"
    case "home_icon":
      return "🏠"
    case "bus_icon":
      return "🚕"
    case "game_icon":
      return "🎮"
    case "med_icon":
      return "💊"
    case "shop_icon":
      return "🛍️"
    case "bolt_icon":
      return "⚡"
    case "chart_icon":
      return "📊"
  }
}